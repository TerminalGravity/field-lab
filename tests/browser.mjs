import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,executablePath:'/run/current-system/sw/bin/chromium',args:['--no-sandbox']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4178/course/',{waitUntil:'networkidle'});
 assert.equal(await page.getByRole('heading',{name:'Tokens & the bill.'}).count(),1);
 await page.getByRole('tab',{name:'Interactive lab'}).click();
 assert.ok((await page.getByText('ESTIMATED TOTAL · STANDARD RATES').count())>0);
 await page.getByRole('tab',{name:'Knowledge check'}).click();
 await page.getByRole('button',{name:/Workload cost also depends/}).click();
 assert.ok((await page.getByText('Correct.').count())>0);
 await page.getByRole('button',{name:/Mark complete & continue/}).click();
 assert.equal(await page.getByRole('heading',{name:'Prompt caching.'}).count(),1);
 await page.reload({waitUntil:'networkidle'});
 assert.ok((await page.getByText('1 / 4').count())>0);
 await page.getByRole('button',{name:/Prompt caching/}).click();
 await page.getByRole('tab',{name:'Interactive lab'}).click();
 await page.getByLabel('Time between calls').selectOption('8');
 assert.ok((await page.getByText('0 of 10 calls read the prefix').count())>0);
 await page.getByLabel('Claude cache lifetime').selectOption('60');
 assert.ok((await page.getByText('9 of 10 calls read the prefix').count())>0);
 await page.getByRole('button',{name:/The model ladder/}).click();
 await page.getByRole('tab',{name:'Interactive lab'}).click();
 await page.getByRole('button',{name:/High-volume extraction/}).click();
 assert.equal(await page.getByRole('heading',{name:'GPT-6 Luna'}).count(),1);
 await page.getByRole('button',{name:/Agent economics/}).click();
 await page.getByRole('tab',{name:'Interactive lab'}).click();
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export CSV'}).click();
 const download=await downloadPromise;assert.equal(download.suggestedFilename(),'agent-economics.csv');
 assert.equal(await page.locator('tbody tr').count(),15);
 const mobile=await browser.newPage({viewport:{width:390,height:844}});
 await mobile.goto('http://127.0.0.1:4178/course/',{waitUntil:'networkidle'});
 await mobile.getByRole('button',{name:'Open navigation'}).click();
 await mobile.getByRole('button',{name:/Prompt caching/}).click();
 assert.equal(await mobile.getByRole('heading',{name:'Prompt caching.'}).count(),1);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({browser:'chromium',quiz:true,persistence:true,cacheTTL:true,routing:true,csv:true,mobileNav:true,pageErrors:errors},null,2));
}finally{await browser.close()}
